import { expect, test } from '@playwright/test';
import { readFileSync, writeFileSync } from 'node:fs';
const directory = '../audit/2026-10-13/activity-photo-workflow';
test('live isolated trip visibly retains provider photos, accepts time edits, reopens and refreshes', async ({ page }) => {
  test.skip(process.env.TRAVELMATE_LIVE_PHOTO_VERIFY !== '1', 'Requires the disposable real-provider verification service.');
  test.setTimeout(120000);
  const trip = JSON.parse(readFileSync(directory + '/live-final-trip.json', 'utf8'));
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(`${process.env.TRAVELMATE_PHOTO_VERIFY_URL || 'http://localhost:3002'}/dashboard?tab=planner&trip=${trip.id}&from=saved`);
  const card = page.locator('[data-daily-card]');
  await expect(card).toHaveCount(1);
  await card.scrollIntoViewIfNeeded();
  await card.screenshot({ path: directory + '/live-overview.png' });
  await card.getByRole('button', { name: 'View Itinerary', exact: true }).click();
  const details = page.locator('[data-day-details]');
  await expect(details.getByRole('heading', { name: 'Arc de Triomphe', exact: true })).toBeVisible();
  await expect(details.getByRole('heading', { name: 'Lunch', exact: true })).toBeVisible();
  await expect(details.getByRole('heading', { name: 'Private appointment (photo-free verification)', exact: true })).toBeVisible();
  const original = trip.itinerary.days[0].activities.find((item: { title: string }) => item.title === 'Arc de Triomphe');
  await details.getByRole('button', { name: `Edit ${original.title}`, exact: true }).click();
  await page.getByLabel('Time', { exact: true }).fill('04:00 PM');
  await page.getByRole('button', { name: 'Save activity', exact: true }).click();
  const save = page.waitForResponse(response => new URL(response.url()).pathname === '/api/platform' && response.request().method() === 'POST');
  await page.getByRole('button', { name: 'Update saved trip', exact: true }).click();
  const saved = (await (await save).json()).result;
  const savedActivity = saved.itinerary.days[0].activities.find((item: { id: string }) => item.id === original.id);
  expect(savedActivity.imageUrl).toBe(original.imageUrl);
  expect(savedActivity.imageAttribution).toEqual(original.imageAttribution);
  await page.reload();
  await expect(details.getByRole('heading', { name: original.title, exact: true })).toBeVisible();
  await expect(details).toContainText('4:00 PM');
  await details.locator('ol').screenshot({ path: directory + '/live-details-refreshed.png', style: 'header { visibility: hidden; }' });
  const imagery = await details.locator('img').evaluateAll(images => images.map(image => ({ src: (image as HTMLImageElement).src, loaded: (image as HTMLImageElement).naturalWidth > 0, alt: (image as HTMLImageElement).alt })));
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await details.screenshot({ path: directory + '/live-mobile.png' });
  writeFileSync(directory + '/live-ui-results.json', JSON.stringify({ tripId: trip.id, preservedPhotoAfterTimeEdit: true, refreshed: true, imagery, errors }, null, 2));
  expect(errors).toEqual([]);
});
