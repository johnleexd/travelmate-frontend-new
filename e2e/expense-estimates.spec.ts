import { test, expect } from '@playwright/test';
import { setup } from './fixtures/planner-fixture';
import { expenseLedger } from '../lib/generated/expense-ledger';
import type { ItineraryResponse } from '../lib/contracts';

test('generation, day totals, Budget review, explicit nightly edits and refresh share one calculation', async ({ page, context }) => {
  const state = await setup(page, context);
  const errors: string[] = []; page.on('pageerror', error=>errors.push(error.message));
  await page.goto('/dashboard?tab=planner');
  await page.locator('#trip-start-date').fill('2040-01-25');
  await page.locator('#trip-end-date').fill('2040-01-27');
  await page.locator('#destination-search').fill('Tokyo');
  await page.locator('#destination-suggestions').getByRole('button').filter({ hasText:'Japan' }).first().click();
  await page.locator('#trip-budget').fill('1000');
  await expect(page.locator('#transportation, #trip-interests, #trip-stay-preference, #trip-preferred-activities')).toHaveCount(0);
  await page.getByRole('button',{ name:'Generate my trip',exact:true }).click();
  await expect.poll(()=>state.saved).not.toBeNull();
  const saved = state.saved!.itinerary;
  expect(saved.grounding!.nights).toBe(2);
  expect(saved.grounding!.accommodation.status).toBe('allowance');
  expect(saved.grounding!.categories.accommodation).toBe(24000);
  const review = expenseLedger(saved as unknown as ItineraryResponse); expect(review.status).toBe('over-budget');
  expect(review.total).toBe(52800); expect(review.allowanceTotal).toBe(52800);
  await expect(page.getByRole('region',{name:'Trip expense estimate'})).toContainText('JPY 52,800');
  await expect(page.getByRole('region',{name:'Trip expense estimate'})).toContainText('Suggested allowance');
  await expect(page.getByRole('region',{name:'Trip expense estimate'})).toContainText('Over budget');
  await expect(page.getByText(/Saved to your trips\./)).toBeVisible();
  await expect(page.getByText('Accommodation planning estimate',{exact:true})).not.toBeVisible();
  await page.getByText('Trip budget & sources',{exact:true}).click();
  await expect(page.getByRole('region',{name:'Accommodation planning estimate'})).toBeVisible();
  await page.getByText('Trip budget & sources',{exact:true}).click();
  await page.getByRole('button',{name:'Budget review',exact:true}).click();
  await expect(page.locator('[data-budget-amount="cost"]')).toHaveText('JPY 52,800');
  await expect(page.locator('[data-budget-amount="remaining"]')).toHaveText('JPY 51,800');
  await expect(page.getByText('Amount over budget',{exact:true})).toBeVisible();
  await expect(page.locator('[data-budget-category="accommodation"]')).toContainText('JPY 24,000');
  await expect(page.locator('[data-budget-category="accommodation"]')).toContainText('Suggested allowance included');
  await expect(page.getByText('For planning purposes only. Actual prices may vary.',{exact:true})).toBeVisible();
  await page.evaluate(()=>window.scrollTo(0,0));
  await expect.poll(()=>page.evaluate(()=>window.scrollY)).toBe(0);
  await page.screenshot({path:'test-results/estimates-budget-review.png',fullPage:true});
  await page.getByRole('button',{name:'Back to itinerary',exact:true}).click();
  await page.getByText('Trip planning settings',{exact:true}).click();
  await page.getByText('Budget details (optional)',{exact:true}).click();
  await page.getByText('Expense assumptions (optional)',{exact:true}).click();
  await page.locator('[name="expense-nightlyRoomEstimate"]').fill('5000');
  const before=state.writes.length;
  await page.getByRole('button',{name:'Update saved trip',exact:true}).click();
  await expect.poll(()=>state.writes.length).toBe(before+1);
  await expect.poll(()=>state.saved!.itinerary.accommodationEstimate?.unitAmount).toBe(5000);
  expect(state.saved!.itinerary.days.map(day=>day.activities)).toEqual(saved.days.map(day=>day.activities));
  expect(state.generations).toHaveLength(1);
  await page.reload();
  await expect(page.getByRole('region',{name:'Trip expense estimate'})).toContainText('JPY 37,400');
  await page.getByText('Trip planning settings',{exact:true}).click();
  await page.getByText('Budget details (optional)',{exact:true}).click();
  await page.getByText('Expense assumptions (optional)',{exact:true}).click();
  await expect(page.locator('[name="expense-nightlyRoomEstimate"]')).toHaveValue('5000');
  await page.setViewportSize({width:390,height:1000});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
  expect(errors).toEqual([]);
});

test('a saved trip with missing estimates stays partial without writes or automatic regeneration', async ({ page, context }) => {
  const state=await setup(page,context);
  // Generate a fixture through the UI, then keep its historical unpriced metadata.
  await page.goto('/dashboard?tab=planner');
  await page.locator('#destination-search').fill('Tokyo');
  await page.locator('#destination-suggestions').getByRole('button').filter({hasText:'Japan'}).first().click();
  await page.locator('#trip-end-date').fill(await page.locator('#trip-start-date').inputValue());
  await page.locator('#trip-budget').fill('100000');
  await page.getByRole('button',{name:'Generate my trip',exact:true}).click();
  await expect.poll(()=>state.saved).not.toBeNull();
  const trip=state.saved!;
  trip.itinerary.days[0].activities[0].priceEvidence!.status='unavailable';
  trip.itinerary.days[0].activities[0].estimatedCost=0;
  const historical=structuredClone(trip), writes=state.writes.length, generations=state.generations.length;
  await page.reload();
  await expect(page.getByRole('region',{name:'Trip expense estimate'})).toContainText('Total estimated cost (partial)');
  await page.getByRole('button',{name:'Budget review',exact:true}).click();
  await expect(page.getByText('Total estimated cost (partial)',{exact:true}).first()).toBeVisible();
  await expect(page.getByText(/Provisional.*affordability needs confirmation/)).toBeVisible();
  await expect(page.getByText('Within your estimated budget',{exact:true})).toHaveCount(0);
  await expect(page.locator('[data-budget-category="food"]')).toContainText('Estimate unavailable');
  expect(state.saved).toEqual(historical); expect(state.writes).toHaveLength(writes); expect(state.generations).toHaveLength(generations);
});
